'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
let checks = 0;
const check = (value) => { assert.ok(value); checks++; };
const input = {type: 'password', value: ' Synthetic password 🌍 '};
let click; const attrs = {};
const button = {hidden: true, addEventListener: (event, fn) => { assert.equal(event, 'click'); click = fn; }, setAttribute: (key, value) => { attrs[key] = value; }};
let slashToggled = false;
const slash = {hidden: true, toggleAttribute: (name, hidden) => { assert.equal(name, 'hidden'); slash.hidden = hidden; slashToggled = true; }}; let focused = false;
const nodes = {'password': input, 'password-visibility': button, 'visibility-slash': slash, 'error-summary': {focus: () => { focused = true; }}};
const code = fs.readFileSync(path.join(root, 'public/assets/login.js'), 'utf8');
vm.runInNewContext(code, {document: {getElementById: (id) => nodes[id]}});
check(!button.hidden); click(); check(input.type === 'text'); check(attrs['aria-label'] === 'Hide password'); check(attrs['aria-pressed'] === 'true'); check(!slash.hidden); check(slashToggled);
click(); check(input.type === 'password'); check(attrs['aria-label'] === 'Show password'); check(input.value === ' Synthetic password 🌍 '); check(focused);
vm.runInNewContext(code, {document: {getElementById: () => null}}); checks++;
const view = fs.readFileSync(path.join(root, 'app/Views/login.php'), 'utf8');
check(view.includes('type="button"'));check(view.includes('autocomplete="current-password"'));check(view.includes('autocomplete="username"'));check(!view.includes('value="<?= $escape($password)'));
check(view.includes('aria-describedby="password-error"'));check(view.includes('tabindex="-1"'));
console.log(`PASS: ${checks} authentication UI fixture checks; no actual browser or database.`);
